use std::error::Error;
use std::path::{Path, PathBuf};
use std::process::Command;

use wyldtone_plugin_api::config::{CppConfig, AudioBuses};
use std::fs;

// Only the mandatory legacy ABI exports belong here. Optional extensions
// (including the stereo/multi-bus ABI) are exported by the plugin itself
// with WASM_PLUGIN_EXPORT / EMSCRIPTEN_KEEPALIVE.
const REQUIRED_EXPORTS: &[&str] = &[
    "_plugin_init",
    "_plugin_name",
    "_plugin_buffer_ptr",
    "_plugin_process",
    "_plugin_parameter_count",
    "_plugin_parameter_id",
    "_plugin_parameter_name",
    "_plugin_parameter_label",
    "_plugin_parameter_min",
    "_plugin_parameter_max",
    "_plugin_parameter_default",
    "_plugin_parameter_step",
    "_plugin_parameter_flags",
    "_plugin_parameter_get",
    "_plugin_parameter_set",
    "_plugin_pending_events",
];

fn exported_functions_setting() -> String {
    let symbols: Vec<String> = REQUIRED_EXPORTS
        .iter()
        .map(|name| format!("'{name}'"))
        .collect();
    format!("EXPORTED_FUNCTIONS=[{}]", symbols.join(","))
}


const BUS_EXPORTS: &[&str] = &[
    "_plugin_input_bus_count", "_plugin_output_bus_count",
    "_plugin_input_bus_channels", "_plugin_output_bus_channels",
];

fn all_exports_setting() -> String {
    let items = REQUIRED_EXPORTS.iter().chain(BUS_EXPORTS.iter())
        .map(|s| format!("'{s}'")).collect::<Vec<_>>().join(",");
    format!("EXPORTED_FUNCTIONS=[{items}]")
}

fn generated_bus_source(layout: &AudioBuses) -> String {
    fn channels(values: &[u32]) -> String {
        if values.is_empty() { return "return 0;".into(); }
        let mut text = "switch (index) {".to_string();
        for (i, v) in values.iter().enumerate() {
            text.push_str(&format!(" case {i}: return {v};"));
        }
        text.push_str(" default: return 0; }");
        text
    }
    format!(r#"// Generated by Wyldtone SDK. Do not edit.
#include <stdint.h>
#ifdef __EMSCRIPTEN__
#include <emscripten/emscripten.h>
#define WYLD_EXPORT EMSCRIPTEN_KEEPALIVE
#else
#define WYLD_EXPORT
#endif
extern "C" {{
WYLD_EXPORT __attribute__((weak)) int32_t plugin_input_bus_count(void) {{ return {}; }}
WYLD_EXPORT __attribute__((weak)) int32_t plugin_output_bus_count(void) {{ return {}; }}
WYLD_EXPORT __attribute__((weak)) int32_t plugin_input_bus_channels(int32_t index) {{ {} }}
WYLD_EXPORT __attribute__((weak)) int32_t plugin_output_bus_channels(int32_t index) {{ {} }}
}}
"#, layout.inputs.len(), layout.outputs.len(), channels(&layout.inputs), channels(&layout.outputs))
}

pub fn build(
    config: &CppConfig,
    plugin_dir: &Path,
    output: &Path,
    audio: Option<&AudioBuses>,
) -> Result<(), Box<dyn Error>> {
    let output_path = output.with_extension("wasm");

    let include_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../abi/include");

    if !include_dir.is_dir() {
        return Err(format!(
            "WASM plugin include directory does not exist: {}",
            include_dir.display()
        )
        .into());
    }

    let mut command = Command::new("em++");

    command
        .arg("-O2")
        .arg("-I")
        .arg(&include_dir)
        .arg("--no-entry")
        .arg("-s")
        .arg("STANDALONE_WASM=1")
        .arg("-s")
        .arg(if audio.is_some() { all_exports_setting() } else { exported_functions_setting() });

    for source in &config.sources {
        let source_path = plugin_dir.join(source);

        if !source_path.is_file() {
            return Err(format!(
                "C++ source file does not exist: {}",
                source_path.display()
            )
            .into());
        }

        command.arg(source_path);
    }

    // Generated weak definitions permit old plugins to provide strong, hand-written
    // exports. The post-build inspector validates that such overrides match config.
    if let Some(layout) = audio {
        layout.validate()?;
        let generated = output_path.with_file_name("wyldtone_generated_buses.cpp");
        fs::write(&generated, generated_bus_source(layout))?;
        command.arg(&generated);
        // The generated exports are explicitly included by all_exports_setting().
    }

    command.arg("-o").arg(&output_path);

    println!("Building C++ WASM plugin...");

    let status = command.status()?;

    if !status.success() {
        return Err("C++ WASM build failed".into());
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exported_functions_have_no_empty_entry() {
        let setting = exported_functions_setting();
        assert!(setting.starts_with("EXPORTED_FUNCTIONS=['_plugin_init',"));
        assert!(setting.ends_with("'_plugin_pending_events']"));
        assert!(!setting.contains(",]"));
        assert_eq!(setting.matches("'_plugin_").count(), REQUIRED_EXPORTS.len());
    }

    #[test]
    fn generated_stereo_metadata() {
        let src = generated_bus_source(&AudioBuses {inputs:vec![2],outputs:vec![2]});
        assert!(src.contains("plugin_input_bus_count(void) { return 1; }"));
        assert!(src.contains("case 0: return 2;"));
    }
    #[test]
    fn mandatory_exports_are_unique() {
        let mut exports = REQUIRED_EXPORTS.to_vec();
        exports.sort_unstable();
        exports.dedup();
        assert_eq!(exports.len(), REQUIRED_EXPORTS.len());
    }
}
