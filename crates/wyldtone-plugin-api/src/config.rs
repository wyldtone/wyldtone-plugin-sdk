use serde::Deserialize;

#[derive(Debug, Clone, Copy)]
pub struct AudioConfig {
    pub sample_rate: u32,
    pub channels: u16,
    pub buffer_size: u32,
}

#[derive(Debug, Clone, Deserialize)]
pub struct PluginConfig {
    pub id: String,
    pub name: String,
    pub manufacturer: String,
    pub version: String,

    /// Optional library section, e.g. "Dynamics" or "Drive".
    #[serde(default)]
    pub category: Option<String>,
    /// Optional plain-text description for plugin catalogs and inspectors.
    #[serde(default)]
    pub description: Option<String>,
    /// Optional relative path to SVG (theme-colored) or PNG (original colors).
    /// By default, icon.svg is preferred over icon.png in the plugin directory.
    #[serde(default)]
    pub icon: Option<String>,

    pub juce: Option<JuceConfig>,
    pub cpp: Option<CppConfig>,
    #[serde(default)]
    pub faust: Option<FaustConfig>,
    /// Optional explicit audio buses. Each entry specifies channels in one bus.
    /// For example {"inputs":[2],"outputs":[2]} is stereo in/out.
    #[serde(default)]
    pub audio: Option<AudioBuses>,
}

#[derive(Debug, Clone, Deserialize)]
pub struct JuceConfig {
    pub processor: String,
    pub header: String,
    #[serde(default)]
    pub modules: Vec<String>,
    /// Additional header-only dependency include directories, relative to
    /// the original plugin root (e.g. libs/chowdsp_wdf/include).
    #[serde(default)]
    pub include_dirs: Vec<String>,
    /// Enable standard WebAssembly SIMD128 during compile/link.
    #[serde(default)]
    pub simd128: bool,
    #[serde(default)]
    pub mode: JuceMode,
}

#[derive(Debug, Clone, Deserialize)]
pub struct FaustConfig {
    pub source: String,
    /// Optional extra signal inputs generated by a native C++ controller.
    /// These are internal DSP inputs, not additional host audio buses.
    #[serde(default)]
    pub extra_inputs: u32,
    /// Plugin-local C++ source files implementing the optional control-input hook.
    #[serde(default)]
    pub extra_sources: Vec<String>,
}

#[derive(Debug, Clone, Deserialize)]
pub struct CppConfig {
    pub sources: Vec<String>,
}
#[derive(Debug, Clone, Copy, Default, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum JuceMode {
    #[default]
    Headless,
    Full,
}

/// The static bus layout written into generated WASM metadata exports.
#[derive(Debug, Clone, PartialEq, Eq, serde::Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AudioBuses {
    pub inputs: Vec<u32>,
    pub outputs: Vec<u32>,
}

impl AudioBuses {
    pub fn validate(&self) -> Result<(), String> {
        if self.inputs.len() > 32 || self.outputs.len() > 32 {
            return Err("Audio bus count must not exceed 32".into());
        }
        if self.inputs.is_empty() && self.outputs.is_empty() {
            return Err("At least one input or output bus is required".into());
        }
        for (direction, buses) in [("input", &self.inputs), ("output", &self.outputs)] {
            for (index, &channels) in buses.iter().enumerate() {
                if channels == 0 || channels > 64 {
                    return Err(format!("{direction} bus {index}: channels must be 1..=64"));
                }
            }
        }
        Ok(())
    }
}

#[cfg(test)]
mod audio_tests {
    use super::*;
    #[test]
    fn accepts_mono_stereo_and_multiple_buses() {
        for (ins, outs) in [(vec![1],vec![1]),(vec![2],vec![2]),(vec![2,1],vec![2])]{
            AudioBuses{inputs:ins,outputs:outs}.validate().unwrap();
        }
    }
    #[test]
    fn rejects_invalid_channels() {
        assert!(AudioBuses{inputs:vec![0],outputs:vec![2]}.validate().is_err());
        assert!(AudioBuses{inputs:vec![65],outputs:vec![2]}.validate().is_err());
        assert!(AudioBuses{inputs:vec![],outputs:vec![]}.validate().is_err());
    }
}
